#!/usr/bin/env node
import { constants } from "node:fs"
import { access, mkdir, readdir, readFile, writeFile } from "node:fs/promises"
import { join } from "node:path"
import { fileURLToPath } from "node:url"
import { build, context } from "esbuild"

const root = fileURLToPath(new URL("..", import.meta.url))
const packagesRoot = join(root, "packages")
const watch = process.argv.includes("--watch")

async function fileExists(path) {
  try {
    await access(path, constants.F_OK)
    return true
  } catch {
    return false
  }
}

/**
 * Wrap a CommonJS bundle in the classic-script factory the DSH client module
 * loader expects. The wrapped bundle must stay a classic script: it calls
 * `window.__ModuleLoader__.load` synchronously and returns the module exports.
 */
function wrapClient(id, code) {
  const body = code
    .split("\n")
    .map((line) => (line.length > 0 ? `\t\t${line}` : ""))
    .join("\n")
  return [
    "/* Generated by scripts/build.mjs — do not edit. */",
    "window.__ModuleLoader__.load({",
    `\tid: ${JSON.stringify(id)},`,
    "\tfactory: (require) => {",
    "\t\tvar module = { exports: {} };",
    "\t\tvar exports = module.exports;",
    body,
    "\t\treturn module.exports;",
    "\t}",
    "});",
    "",
  ].join("\n")
}

async function buildPackage(name) {
  const packageDir = join(packagesRoot, name)
  const manifest = JSON.parse(await readFile(join(packageDir, "package.json"), "utf8"))
  const outDir = join(packageDir, "lib")
  const targetDir = join(packageDir, "src")
  const hostEntry = join(targetDir, "index.ts")
  const clientTsx = join(targetDir, "client/index.tsx")
  const clientTs = join(targetDir, "client/index.ts")
  const clientEntry = (await fileExists(clientTsx))
    ? clientTsx
    : (await fileExists(clientTs))
      ? clientTs
      : undefined

  const hasHost = await fileExists(hostEntry)
  if (!hasHost && clientEntry === undefined) return

  await mkdir(outDir, { recursive: true })

  if (hasHost) {
    const options = {
      entryPoints: [hostEntry],
      outfile: join(outDir, "index.js"),
      bundle: true,
      packages: "external",
      format: "esm",
      platform: "neutral",
      target: "es2022",
      logLevel: "warning",
    }
    if (watch) {
      const buildContext = await context({
        ...options,
        plugins: [
          {
            name: "log-host",
            setup(buildApi) {
              buildApi.onEnd((result) => {
                if (result.errors.length === 0) console.log(`rebuilt ${name}/lib/index.js`)
              })
            },
          },
        ],
      })
      await buildContext.watch()
    } else {
      await build(options)
      console.log(`built ${name}/lib/index.js`)
    }
  }

  if (clientEntry !== undefined) {
    const outfile = join(outDir, "client.js")
    const options = {
      entryPoints: [clientEntry],
      bundle: true,
      packages: "external",
      format: "cjs",
      platform: "browser",
      target: "es2020",
      jsx: "automatic",
      logLevel: "warning",
      write: false,
    }
    if (watch) {
      const buildContext = await context({
        ...options,
        plugins: [
          {
            name: "wrap-client",
            setup(buildApi) {
              buildApi.onEnd(async (result) => {
                if (result.errors.length > 0) return
                const code = result.outputFiles?.[0]?.text ?? ""
                await writeFile(outfile, wrapClient(manifest.name, code))
                console.log(`rebuilt ${name}/lib/client.js`)
              })
            },
          },
        ],
      })
      await buildContext.watch()
    } else {
      const result = await build(options)
      const code = result.outputFiles?.[0]?.text ?? ""
      await writeFile(outfile, wrapClient(manifest.name, code))
      console.log(`built ${name}/lib/client.js`)
    }
  }
}

const entries = (await readdir(packagesRoot, { withFileTypes: true }))
  .filter((entry) => entry.isDirectory())
  .map((entry) => entry.name)
  .sort()

for (const name of entries) await buildPackage(name)

if (watch) {
  console.log("watching packages/*/src — press Ctrl+C to stop")
} else {
  console.log("build complete")
}
